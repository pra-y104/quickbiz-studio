/**
 * Project persistence.
 *
 * Phase 1 is deliberately local: projects live in this browser's IndexedDB, so
 * the editor works with no account, no server and no cost. The interface must
 * say so, because local data is lost when site data is cleared or the browser is
 * changed. Cloud persistence is a separate, approved milestone.
 *
 * `createInMemoryProjectStore` backs the tests and gives the same contract, so
 * every consumer is written against the interface rather than IndexedDB.
 */

import type { CreativeDocument } from '@quickbiz/shared';
import { ASSET_STORE, PROJECT_STORE, openDatabase, runRequest } from './idb';

export interface CreativeProjectRecord {
  readonly id: string;
  readonly title: string;
  readonly document: CreativeDocument;
  /** PNG data URL, generated by the editor. Absent for older records. */
  readonly thumbnail?: string;
  readonly createdAt: string;
  readonly updatedAt: string;
}

export interface CreativeProjectSummary {
  readonly id: string;
  readonly title: string;
  readonly updatedAt: string;
  readonly createdAt: string;
  readonly thumbnail?: string;
  readonly nodeCount: number;
  readonly presetLabel: string;
}

export interface CreativeProjectStore {
  /** True when writes survive a reload. */
  readonly persistent: boolean;
  list(): Promise<readonly CreativeProjectSummary[]>;
  get(id: string): Promise<CreativeProjectRecord | null>;
  put(record: CreativeProjectRecord): Promise<void>;
  remove(id: string): Promise<void>;
}

const MAX_SUMMARIES = 100;

function sortByRecency(records: readonly CreativeProjectRecord[]): CreativeProjectRecord[] {
  return [...records].sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));
}

function summarise(record: CreativeProjectRecord, presetLabel: string): CreativeProjectSummary {
  return {
    id: record.id,
    title: record.title,
    updatedAt: record.updatedAt,
    createdAt: record.createdAt,
    ...(record.thumbnail === undefined ? {} : { thumbnail: record.thumbnail }),
    nodeCount: countNodes(record.document),
    presetLabel,
  };
}

function countNodes(document: CreativeDocument): number {
  let total = 0;
  for (const node of document.nodes) {
    total += 1;
    if (node.type === 'group') total += node.children.length;
  }
  return total;
}

/** IndexedDB-backed store used by the application. */
export function createIndexedDbProjectStore(): CreativeProjectStore {
  return {
    persistent: true,

    async list() {
      const database = await openDatabase();
      const records = await runRequest<CreativeProjectRecord[]>({
        database,
        store: PROJECT_STORE,
        mode: 'readonly',
        operation: (store) => store.getAll() as IDBRequest<CreativeProjectRecord[]>,
      });
      return sortByRecency(records)
        .slice(0, MAX_SUMMARIES)
        .map((record) => summarise(record, describeCanvas(record.document)));
    },

    async get(id) {
      const database = await openDatabase();
      const record = await runRequest<CreativeProjectRecord | undefined>({
        database,
        store: PROJECT_STORE,
        mode: 'readonly',
        operation: (store) => store.get(id) as IDBRequest<CreativeProjectRecord | undefined>,
      });
      return record ?? null;
    },

    async put(record) {
      const database = await openDatabase();
      await runRequest<IDBValidKey>({
        database,
        store: PROJECT_STORE,
        mode: 'readwrite',
        operation: (store) => store.put(record),
      });
    },

    async remove(id) {
      const database = await openDatabase();
      await runRequest<undefined>({
        database,
        store: PROJECT_STORE,
        mode: 'readwrite',
        operation: (store) => store.delete(id) as IDBRequest<undefined>,
      });
    },
  };
}

/** Test store with identical semantics and no browser dependency. */
export function createInMemoryProjectStore(
  initial: readonly CreativeProjectRecord[] = [],
): CreativeProjectStore & { records: CreativeProjectRecord[] } {
  const records = [...initial];

  return {
    persistent: false,
    records,
    async list() {
      return sortByRecency(records)
        .slice(0, MAX_SUMMARIES)
        .map((record) => summarise(record, describeCanvas(record.document)));
    },
    async get(id) {
      return records.find((record) => record.id === id) ?? null;
    },
    async put(record) {
      const index = records.findIndex((candidate) => candidate.id === record.id);
      if (index >= 0) records[index] = record;
      else records.push(record);
    },
    async remove(id) {
      const index = records.findIndex((candidate) => candidate.id === id);
      if (index >= 0) records.splice(index, 1);
    },
  };
}

function describeCanvas(document: CreativeDocument): string {
  const { unit, width, height } = document.canvas;
  return unit === 'mm' ? `${width} × ${height} mm` : `${width} × ${height} px`;
}

/** Delete an asset and every record that could still reference it. */
export async function removeAsset(assetId: string): Promise<void> {
  const database = await openDatabase();
  await runRequest<undefined>({
    database,
    store: ASSET_STORE,
    mode: 'readwrite',
    operation: (store) => store.delete(assetId) as IDBRequest<undefined>,
  });
}
